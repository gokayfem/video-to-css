#!/usr/bin/env node
// Build-time generator for the wind-farm strict-CSS scene.
// Each part module (build/parts/<name>.mjs) returns { html, css, controls?, tracks? };
// this script assembles them in paint order into scene/index.html + scene/scene.css
// and writes scene.json. The output needs no JavaScript to play.
// Usage: node examples/wind-farm/build/build.mjs
import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const EX = join(HERE, '..');
const ID = 'wind';
const W = 1280, H = 720, LOOP = 10;

// Paint order, back to front. Missing parts are skipped (lets workers build in parallel).
const ORDER = ['sky', 'clouds', 'turbines', 'hill', 'grass', 'flowers', 'paper'];

const ctx = {
  id: ID, W, H, loop: LOOP,
  root: `v2c-${ID}`,
  cls: (part, el = '') => `v2c-${ID}__${part}${el ? '-' + el : ''}`,
  kf: (part, name) => `v2c-${ID}-${part}-${name}`,
  prop: (part, name) => `--v2c-${ID}-${part ? part + '-' : ''}${name}`,
  // duration of something that repeats k times per loop (k integer => seamless loop)
  per: (k) => `calc(var(--v2c-${ID}-loop) / ${k})`,
  // negative delay placing phase fraction `ph` (0..1) of a k-per-loop cycle at t = 0
  phase: (k, ph) => `calc(var(--v2c-${ID}-loop) / ${k} * ${-((ph % 1 + 1) % 1).toFixed(5)})`,
  r: (v, d = 2) => +v.toFixed(d),
};

const parts = [];
for (const name of ORDER) {
  const file = join(HERE, 'parts', `${name}.mjs`);
  if (!existsSync(file)) { console.log(`  (skip ${name}: not built yet)`); continue; }
  const mod = await import(file + `?t=${Date.now()}`);
  const out = await mod.default(ctx);
  parts.push({ name, ...out });
  console.log(`  ${name}: ${(out.html.match(/<[a-z]/g) || []).length} elements, ${out.css.length} B css`);
}

// Controls are declared once, on the root, so a value set on the root (inline style, host
// page, review page) reaches every consumer. Part-level declarations of control properties
// would shadow the inherited value, so they are stripped here.
const controlDefaults = parts.flatMap((p) => p.controls ?? []);
const esc = (n) => n.replace(/[-]/g, '\\-');
for (const p of parts) for (const c of controlDefaults) p.css = p.css.replace(new RegExp(`(^|[;{\\s])${esc(c.name)}\\s*:[^;{}]*;`, 'g'), '$1');
const css = `/* video-to-css — wind farm ridge (strict HTML/CSS profile)
   Generated by examples/wind-farm/build/build.mjs from build/parts/*.mjs; edit those, not this file.
   Reference: user-supplied Blender render (Video2Nodes wind-farm/out/loop_720p.mp4), 1280x720, 10 s loop.
   Scene time t = animation currentTime; every cycle divides the ${LOOP} s loop, so the loop is seamless. */
.v2c-${ID} {
  ${ctx.prop('', 'loop')}: ${LOOP}s;   /* loop length; all motion scales with it */
  ${ctx.prop('', 'wind')}: 1;      /* wind strength multiplier for grass/flowers */
${controlDefaults.map((c) => `  ${c.name}: ${c.default};   /* ${c.description} */`).join('\n')}
  position: relative; width: ${W}px; height: ${H}px; overflow: hidden; isolation: isolate;
  contain: layout paint;
}
.v2c-${ID} .v2c-${ID}__layer { position: absolute; inset: 0; }
${parts.map((p) => `\n/* ---------------- ${p.name} ---------------- */\n${p.css.trim()}\n`).join('')}
/* Reduced motion: every animation holds its t = 0 pose (negative delays keep it representative). */
@media (prefers-reduced-motion: reduce) {
  .v2c-${ID}, .v2c-${ID} *, .v2c-${ID} *::before, .v2c-${ID} *::after { animation-play-state: paused !important; }
}
`;
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Wind farm ridge — video-to-css</title>
<link rel="stylesheet" href="scene.css">
<style>body{margin:0}</style>
</head>
<body>
<div class="v2c-${ID}" role="img" aria-label="Painted wind farm on a green ridge: turbines turning, clouds drifting, grass in the wind">
${parts.map((p) => `<div class="v2c-${ID}__layer v2c-${ID}__layer--${p.name}">\n${p.html.trim()}\n</div>`).join('\n')}
</div>
</body>
</html>
`;
writeFileSync(join(EX, 'scene', 'scene.css'), css);
writeFileSync(join(EX, 'scene', 'index.html'), html);

const base = JSON.parse(readFileSync(join(HERE, 'scene.base.json'), 'utf8'));
base.controls = [...base.controls, ...parts.flatMap((p) => p.controls ?? [])];
base.tracks = parts.flatMap((p) => p.tracks ?? []);
writeFileSync(join(EX, 'scene.json'), JSON.stringify(base, null, 2) + '\n');
const elements = (html.match(/<[a-z]/g) || []).length;
console.log(`scene: ${elements} elements, ${css.length} B css -> ${join(EX, 'scene')}`);
