// Scaffold a scene package for any clip: measured stage size, timing window, loop guess,
// a reference contact sheet, and a starter scene that already passes the strict audit.
import { existsSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { basename, extname, join, relative, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { inspectClip, extractFrames } from './video.mjs';
import { readPNG } from './png.mjs';
import { meanAbsDiff } from './metrics.mjs';
import { GATES } from './compare.mjs';
import { run, ensureDir, writeJSON, findRoot, fmt } from './util.mjs';

const TEMPLATES = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'templates');

export const slug = (name) => {
  const s = name.toLowerCase().replace(/\.[a-z0-9]+$/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '').slice(0, 24).replace(/-+$/, '');
  return /^[a-z]/.test(s) ? s : `s-${s || 'scene'}`;
};

const hex = (r, g, b) => '#' + [r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('');

// Mean colour of `bands` horizontal bands: a measured starting background (top -> bottom).
function bandColors(img, bands = 5) {
  return Array.from({ length: bands }, (_, b) => {
    const y0 = Math.floor((b * img.height) / bands), y1 = Math.floor(((b + 1) * img.height) / bands);
    let r = 0, g = 0, bl = 0, n = 0;
    for (let y = y0; y < y1; y++) for (let x = 0; x < img.width; x++) {
      const i = (y * img.width + x) * 4;
      r += img.data[i]; g += img.data[i + 1]; bl += img.data[i + 2]; n++;
    }
    return hex(r / n, g / n, bl / n);
  });
}

export async function initScene(clipArg, { out, id, start = 0, duration, loop, force = false, log = console.log } = {}) {
  const clip = resolve(clipArg);
  const src = await inspectClip(clip);
  id = id ?? slug(basename(clip, extname(clip)));
  if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(`scene id "${id}" must match [a-z][a-z0-9-]*`);
  const dir = resolve(out ?? id);
  if (existsSync(join(dir, 'scene.json')) && !force) throw new Error(`${dir}/scene.json exists (use --force to overwrite)`);
  start = Number(start);
  const span = src.duration - start;
  duration = Number(duration ?? span);
  if (!(start >= 0 && duration > 0 && start + duration <= src.duration + 1e-6)) {
    throw new Error(`window ${start}+${duration}s is outside the clip (0–${fmt(src.duration)} s)`);
  }
  const W = src.width, H = src.height;
  const root = findRoot(dir);
  const work = ensureDir(join(root, 'artifacts', id, 'init'));

  // Loop guess: the jump last -> first must look like a normal step (vs last -> previous) AND be
  // clearly smaller than how far the clip travels inside the window (last vs 1/4, 1/2, 3/4).
  const inWin = src.frames.filter((f) => f.pts - src.startPts >= start - 1e-6 && f.pts - src.startPts < start + duration - 1e-6);
  if (inWin.length < 2) throw new Error('the window holds fewer than 2 frames');
  const pick = [0, inWin.length - 2, inWin.length - 1, ...[0.25, 0.5, 0.75].map((q) => Math.floor(q * (inWin.length - 1)))];
  rmSync(join(work, 'frames'), { recursive: true, force: true });
  const { color, entries } = await extractFrames(src, pick.map((i) => ({ t: inWin[i].pts - src.startPts })), join(work, 'frames'));
  const [first, prev, last, ...mid] = entries.map((e) => readPNG(e.file));
  const step = meanAbsDiff(prev, last), seam = meanAbsDiff(last, first);
  const travel = Math.max(...mid.map((m) => meanAbsDiff(last, m)));
  const seamRatio = seam / Math.max(step, 0.05);
  const travelRatio = travel > 0.05 ? seam / travel : 0;
  const looksLooped = seamRatio <= GATES.seamJumpRatio && travelRatio <= 0.5;
  const isLoop = loop ?? looksLooped;

  // Contact sheet: 8 evenly spaced frames from the window (real decode, display size).
  const sheet = join(work, 'contact.jpg');
  const tw = Math.min(320, W);
  await run('ffmpeg', ['-v', 'error', '-y', '-ss', String(start), '-t', String(duration), '-i', clip,
    '-vf', `fps=${8 / duration},scale=${tw}:-2,tile=4x2`, '-frames:v', '1', '-q:v', '3', sheet]);

  const bands = bandColors(first);
  const sub = (s) => s.replaceAll('ID', id);
  const loopS = +duration.toFixed(3);
  ensureDir(join(dir, 'scene'));
  const title = basename(clip, extname(clip));
  writeFileSync(join(dir, 'scene', 'index.html'), sub(readFileSync(join(TEMPLATES, 'scene', 'index.html'), 'utf8'))
    .replace('SCENE TITLE', title).replace('SHORT DESCRIPTION', `Reconstruction of ${title}`)
    .replace(/\s*<div class="v2c-[a-z0-9-]+__part">.*<\/div>\n/, '\n  <!-- parts go here, back to front (see references/scene-contract.md) -->\n'));
  writeFileSync(join(dir, 'scene', 'scene.css'), `/* video-to-css strict profile — ${title}
   Generated by \`v2css init\`. Stage px = reference display px (${W}x${H}).
   Scene time t = animation currentTime; reference time = t + ${start} s in the clip. */
.v2c-${id} {
  --v2c-${id}-loop: ${loopS}s;   /* runtime control: ${isLoop ? 'loop length' : 'clip length'}; derive every duration from it */
  position: relative; width: ${W}px; height: ${H}px; overflow: hidden; isolation: isolate;
  /* measured: mean colour of 5 horizontal bands of the first frame */
  background: linear-gradient(${bands.map((c, i) => `${c} ${Math.round((100 * (i + 0.5)) / bands.length)}%`).join(', ')});
}
/* layout > parent motion > local pivot > appearance; one keyframes name per motion,
   all prefixed v2c-${id}-, durations as calc(var(--v2c-${id}-loop) / k) */

@media (prefers-reduced-motion: reduce) {
  .v2c-${id} *, .v2c-${id} *::before, .v2c-${id} *::after { animation-play-state: paused !important; }
}
`);

  const scene = {
    id, title, profile: 'strict-css', synthetic: false,
    reference: { clip: relative(dir, clip), sha256: src.sha256 },
    stage: { selector: `.v2c-${id}`, width: W, height: H },
    timing: { duration: loopS, loop: isLoop, offset: start },
    controls: [
      { name: `--v2c-${id}-loop`, kind: 'runtime', type: 'time', unit: 's', default: `${loopS}s`, range: [`${+(loopS / 2).toFixed(3)}s`, `${+(loopS * 2).toFixed(3)}s`], variant: `${+(loopS * 1.5).toFixed(3)}s`, description: isLoop ? 'loop length' : 'clip length' },
    ],
    tracks: [],
  };
  writeJSON(join(dir, 'scene.json'), scene);
  writeJSON(join(dir, 'params.json'), {
    _meta: { source: scene.reference.clip, sha256: src.sha256, units: 'px, s, deg', labels: 'measured|estimated|chosen|fitted', coords: `stage px = display px; frames decoded ${color.rgb ? 'from RGB' : `as ${color.matrix} ${color.range}${color.assumed ? ' (untagged: assumed)' : ''}`}` },
    'clip.window': { value: [start, loopS], unit: 's', label: 'chosen', how: 'v2css init --start/--duration', confidence: 'high' },
    'clip.loop': { value: isLoop, label: loop === undefined ? 'measured' : 'chosen', how: `seam |last-first| ${fmt(seam, 2)} vs step ${fmt(step, 2)} (ratio ${fmt(seamRatio, 2)}, loop if <= ${GATES.seamJumpRatio}) and vs in-window travel ${fmt(travel, 2)} (ratio ${fmt(travelRatio, 2)}, loop if <= 0.5)`, confidence: 'medium' },
    'stage.background': { value: bands, label: 'measured', how: 'mean of 5 horizontal bands, first frame', confidence: 'high' },
  });
  writeFileSync(join(dir, 'REFERENCE.md'), `# ${title} — reference notes

## Provenance
- Clip: \`${scene.reference.clip}\` (relative to this folder). sha256 \`${src.sha256}\`, ${src.bytes} bytes.
- Where it came from: _fill in (AI-generated / camera / render / synthetic) — never call a self-made clip a benchmark._

## Clip facts (measured by \`v2css init\`)
| fact | value |
|---|---|
| container / codec / pixel format | ${src.container} / ${src.codec} / ${src.pixFmt} |
| coded size → display size | ${src.coded.width}×${src.coded.height} → **${W}×${H}** (SAR ${src.sampleAspect ?? '1:1'}, rotation ${src.rotation}°) |
| colour | space ${src.color.space ?? 'untagged'}, range ${src.color.range ?? 'untagged'} → decoded ${color.rgb ? 'as RGB' : `${color.matrix}/${color.range}${color.assumed ? ' (**assumed**)' : ''}`} |
| frames / rate | ${src.frameCount} frames, ${src.variableFrameRate ? `**VFR** (intervals ${src.frameIntervals.min}–${src.frameIntervals.max} s)` : `CFR ${src.avgFrameRate}`} |
| duration | ${fmt(src.duration, 4)} s; scene window ${start}–${fmt(start + duration, 4)} s (${inWin.length} frames) |
| loop seam | last→first ${fmt(seam, 2)} vs normal step ${fmt(step, 2)} (ratio ${fmt(seamRatio, 2)}) and vs travel ${fmt(travel, 2)} (ratio ${fmt(travelRatio, 2)}) → ${looksLooped ? 'looks seamless' : 'not seamless'}; scene \`loop: ${isLoop}\` |

Contact sheet: \`artifacts/${id}/init/contact.jpg\`.

## Inventory and paint order (back to front)
| layer | construction | motion | label |
|---|---|---|---|

## Key measurements
| quantity | value | label | how |
|---|---|---|---|

## Representation limits (honest)
-
`);
  log(`scene package: ${dir}
  stage ${W}x${H}${src.coded.width !== W || src.coded.height !== H ? ` (coded ${src.coded.width}x${src.coded.height}, rotation ${src.rotation}°, SAR ${src.sampleAspect})` : ''}, window ${start}+${loopS} s, ${inWin.length} frames, ${src.variableFrameRate ? 'VFR' : 'CFR'}
  loop: ${isLoop}${loop === undefined ? ` (seam/step ${fmt(seamRatio, 2)}, seam/travel ${fmt(travelRatio, 2)}; override with --loop / --no-loop)` : ' (chosen)'}
  colour: ${color.rgb ? 'RGB source' : `${color.matrix}/${color.range}${color.assumed ? ' (untagged: assumed)' : ''}`}
  contact sheet: ${sheet}${inWin.length > 480 ? `\n  note: ${inWin.length} frames; compare samples 480 of them (set reference.maxSamples)` : ''}
next: look at the contact sheet, fill REFERENCE.md, build parts in scene/, add tracks to scene.json, then
  v2css sbs ${relative(process.cwd(), dir) || '.'} --times 0,${fmt(loopS / 2, 2)}   and   v2css check ${relative(process.cwd(), dir) || '.'}`);
  return { dir, scene, src, seamRatio };
}
